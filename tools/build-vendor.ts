// Bundles vendor-src/entry.ts against a plannotator checkout that sits exactly
// on a release tag, and stamps that version as PINNED_VERSION.
// Usage: bun tools/build-vendor.ts <upstream-checkout> [outfile]
// tools/update-vendor.sh picks the tag from the installed CLI.
import { existsSync } from "node:fs";
import { join, resolve } from "node:path";

const upstream = resolve(process.argv[2] ?? "");
const outfile = resolve(process.argv[3] ?? "mods/plannotator/vendor/plannotator.js");
if (!existsSync(join(upstream, "packages/core"))) throw new Error(`not a plannotator checkout: ${upstream}`);

const git = (...args: string[]) => {
  const run = Bun.spawnSync(["git", "-C", upstream, ...args]);
  if (run.exitCode !== 0) throw new Error(`git ${args.join(" ")}: ${run.stderr.toString().trim()}`);
  return run.stdout.toString().trim();
};
const tag = git("describe", "--tags", "--exact-match", "HEAD");
if (!/^v\d+\.\d+\.\d+$/.test(tag)) throw new Error(`upstream HEAD is not on a release tag: ${tag}`);
if (git("status", "--porcelain", "--untracked-files=no", "--", "packages")) throw new Error(`upstream packages/ has local changes`);
const version = tag.slice(1);

const candidates = (base: string) =>
  [base, `${base}.ts`, `${base}.tsx`, join(base, "index.ts"), join(base, "index.tsx")];

const workspace: import("bun").BunPlugin = {
  name: "plannotator-workspace",
  setup(build) {
    build.onResolve({ filter: /^@plannotator\// }, (args) => {
      const [, pkg, ...rest] = args.path.split("/");
      const base = join(upstream, "packages", pkg, ...rest);
      const hit = candidates(base).find((p) => existsSync(p) && !p.endsWith("/"));
      if (!hit) throw new Error(`unresolved ${args.path} (from ${args.importer})`);
      return { path: hit };
    });
  },
};

const result = await Bun.build({
  entrypoints: [resolve(import.meta.dir, "../vendor-src/entry.ts")],
  format: "esm",
  target: "browser",
  minify: false,
  plugins: [workspace],
  define: { PLANNOTATOR_PINNED_VERSION: JSON.stringify(version) },
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
const banner = `// GENERATED by tools/build-vendor.ts from plannotator ${tag}. Do not edit.\n`;
// Bun names each module by its path from the cwd; keep only the in-repo part so
// the bundle does not change with where the checkout lives.
const code = (await result.outputs[0].text()).replace(/^\/\/ \S*?\/packages\//gm, "// packages/");
await Bun.write(outfile, banner + code);
console.log(`wrote ${outfile} (plannotator ${version})`);
